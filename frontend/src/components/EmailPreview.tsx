"use client";

import { ComposeResult, Track, api } from "@/lib/api";
import { Button, Card } from "./ui";
import { IconExternal, IconFile } from "./icons";

/** The exact message, set as a letter on paper with its attachment below. */
export function EmailPreview({
  rendered,
  recipient,
  gmailUser,
  onBack,
  onSend,
  sending,
  step = 2,
  track = "sd",
}: {
  rendered: ComposeResult;
  recipient: string;
  gmailUser: string;
  onBack: () => void;
  onSend: () => void;
  sending: boolean;
  step?: number;
  track?: Track;
}) {
  const isAI = rendered.source === "ai-tweaked";
  return (
    <Card
      title="Preview"
      step={step}
      action={
        <span
          className="text-[12px] text-[var(--subtle)]"
          title={isAI ? "Your template, with an AI-tailored subject and one company-specific sentence" : "Your fixed template, no AI changes"}
        >
          {isAI ? "Template with AI subject and line" : "Template only"}
        </span>
      }
    >
      {rendered.note && <p className="mb-4 text-[13px] text-[var(--warning-fg)]">{rendered.note}</p>}

      <div className="overflow-hidden rounded-[var(--radius-md)] border border-[var(--border)]">
        <dl className="grid grid-cols-[72px_minmax(0,1fr)] gap-x-3 gap-y-1 border-b border-[var(--border)] bg-[var(--surface)] px-5 py-3 text-[13px]">
          <dt className="text-[var(--subtle)]">From</dt>
          <dd className="truncate text-[var(--fg)]">{gmailUser || "your Gmail"}</dd>
          <dt className="text-[var(--subtle)]">To</dt>
          <dd className="truncate text-[var(--fg)]">{recipient}</dd>
          <dt className="text-[var(--subtle)]">Subject</dt>
          <dd className="font-medium text-[var(--fg)]">{rendered.subject}</dd>
        </dl>

        {/* Paper. Body HTML is trusted: generated by our own backend template. */}
        <div className="bg-[var(--paper)] px-6 py-6 sm:px-8">
          <div
            className="max-w-[64ch] text-[14px] leading-[22px] text-[var(--paper-ink)] [&_a]:underline [&_p]:mb-3"
            dangerouslySetInnerHTML={{ __html: rendered.bodyHTML }}
          />

          <a
            href={api.resumeUrl(track)}
            target="_blank"
            rel="noopener noreferrer"
            className="mt-6 inline-flex items-center gap-3 rounded-[var(--radius-md)] border border-[var(--paper-line)] bg-white/60 py-2 pl-2 pr-3 text-[var(--paper-ink)] transition-colors hover:bg-white"
          >
            <span className="flex h-8 w-8 items-center justify-center rounded-[4px] bg-[#fbede6] text-[#c4421a]">
              <IconFile />
            </span>
            <span className="min-w-0">
              <span className="block truncate font-mono text-[12px]">{rendered.attachmentName}</span>
              <span className="block text-[12px] text-[#7b7266]">From Resumes · {track === "ai" ? "AI" : "SDE"}</span>
            </span>
            <IconExternal size={14} className="text-[#7b7266]" />
          </a>
        </div>
      </div>

      <div className="mt-6 flex flex-wrap items-center gap-3">
        <Button onClick={onSend} loading={sending}>
          Send to {recipient}
        </Button>
        <Button variant="secondary" onClick={onBack} disabled={sending}>
          Edit
        </Button>
        <span className="text-[12px] text-[var(--subtle)]">Sends a real email from your Gmail</span>
      </div>
    </Card>
  );
}
